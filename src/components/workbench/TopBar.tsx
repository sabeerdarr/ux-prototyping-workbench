"use client";
import { useEffect, useRef, useState } from "react";
import { clsx } from "clsx";
import { Check, ChevronDown, CircleCheck, Cloud, CloudOff, Download, FileCode2, FileJson, FileText, FolderOpen, Globe, Layers, Redo2, Undo2 } from "lucide-react";
import { downloadBlob, downloadExport } from "@/lib/client/api";
import { rationaleJson, rationaleMarkdown } from "@/lib/rationale";
import { Button, IconButton, Modal, Pill, Spinner } from "../ui";
import type { Workbench } from "./use-workbench";

function slug(s: string) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "prototype";
}

function ProviderBadge({ wb }: { wb: Workbench }) {
  const [open, setOpen] = useState(false);
  const s = wb.provider;
  if (!s) return null;
  const demo = s.active.id === "demo";
  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className={clsx(
          "inline-flex h-7 items-center gap-1.5 rounded-md border px-2 text-[11.5px] font-medium",
          demo ? "border-amber-300 bg-amber-50 text-amber-900" : "border-wb-line-strong bg-white text-wb-ink-2 hover:text-wb-ink",
        )}
        title="Which generation provider is active"
      >
        <span className={clsx("h-1.5 w-1.5 rounded-full", demo ? "bg-amber-500" : "bg-emerald-500")} aria-hidden="true" />
        {demo ? "Demo mode · no AI" : `${s.active.label} · ${s.active.model}`}
      </button>
      <Modal open={open} onClose={() => setOpen(false)} title="Generation provider">
        <div className="space-y-3 p-4 text-[12.5px] leading-relaxed text-wb-ink-2">
          <p>
            <strong className="text-wb-ink">Active:</strong> {s.active.label}
            {s.active.model ? ` (${s.active.model})` : ""}.{" "}
            {demo
              ? "No ANTHROPIC_API_KEY is configured on the server, so generation loads a prebuilt example and refinements are limited to scripted, rule-based edits. Nothing in demo mode is AI output."
              : "Screens, refinements, annotations, comparisons and reviews are generated by this model through the server-side Anthropic API adapter. Your API key never reaches the browser."}
          </p>
          <p>
            <strong className="text-wb-ink">Claude Design:</strong> not connected. {s.claudeDesign.reason}
          </p>
          <p className="text-[11.5px] text-wb-ink-3">The provider layer is modular (src/lib/ai). If a supported Claude Design integration becomes available, it can be added as another provider without changing the rest of the app.</p>
        </div>
      </Modal>
    </>
  );
}

function ExportMenu({ wb }: { wb: Workbench }) {
  const [open, setOpen] = useState(false);
  const [busy, setBusy] = useState<string | null>(null);
  const ref = useRef<HTMLDivElement>(null);
  const v = wb.viewVersion;
  const p = wb.project;
  useEffect(() => {
    if (!open) return;
    const onDoc = (e: MouseEvent) => ref.current && !ref.current.contains(e.target as Node) && setOpen(false);
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && setOpen(false);
    document.addEventListener("mousedown", onDoc);
    document.addEventListener("keydown", onKey);
    return () => {
      document.removeEventListener("mousedown", onDoc);
      document.removeEventListener("keydown", onKey);
    };
  }, [open]);
  if (!v || !p) return <Button size="sm" variant="secondary" disabled icon={<Download size={13} />}>Export</Button>;

  const base = `${slug(p.name)}-v${v.number}`;
  const meta = { projectName: p.name, versionNumber: v.number, versionLabel: v.label, providerLabel: v.provider.label, approved: p.approvedVersionId === v.id };
  const run = async (id: string, fn: () => Promise<void> | void) => {
    setBusy(id);
    try {
      await fn();
      setOpen(false);
    } catch (err) {
      wb.setError({ kind: "export", message: err instanceof Error ? err.message : "Export failed.", code: "export", retryable: false });
    } finally {
      setBusy(null);
    }
  };
  const items = [
    { id: "html", icon: Globe, label: "Standalone HTML", hint: "Interactive prototype in one file", fn: () => downloadExport("html", { spec: v.spec, meta }, `${base}.html`) },
    { id: "react", icon: FileCode2, label: "React + TypeScript project", hint: "Vite project (.zip) with the renderer and spec", fn: () => downloadExport("react", { spec: v.spec, meta }, `${base}-react.zip`) },
    { id: "md", icon: FileText, label: "Design rationale (Markdown)", hint: "Annotations, assumptions, refinement history", fn: () => downloadBlob(new Blob([rationaleMarkdown(p, v)], { type: "text/markdown" }), `${base}-rationale.md`) },
    { id: "json", icon: FileJson, label: "Design rationale (JSON)", hint: "Structured for other tools", fn: () => downloadBlob(new Blob([JSON.stringify(rationaleJson(p, v), null, 2)], { type: "application/json" }), `${base}-rationale.json`) },
    { id: "spec", icon: Layers, label: "Screen spec (JSON)", hint: "The validated component specification", fn: () => downloadBlob(new Blob([JSON.stringify(v.spec, null, 2)], { type: "application/json" }), `${base}-spec.json`) },
  ];
  return (
    <div className="relative" ref={ref}>
      <Button size="sm" variant="secondary" icon={<Download size={13} />} aria-haspopup="menu" aria-expanded={open} onClick={() => setOpen(!open)}>
        Export <ChevronDown size={12} aria-hidden="true" />
      </Button>
      {open && (
        <div role="menu" className="absolute right-0 z-50 mt-1 w-[300px] rounded-lg border border-wb-line bg-white p-1 shadow-xl">
          <div className="px-2 pt-1.5 pb-1 text-[11px] text-wb-ink-3">
            Exporting v{v.number}
            {wb.isPreviewing ? " (previewed version)" : ""}. Exports are prototypes, not production-ready code.
          </div>
          {items.map((it) => (
            <button key={it.id} role="menuitem" type="button" className="flex w-full items-start gap-2 rounded-md px-2 py-1.5 text-left hover:bg-black/[0.04] disabled:opacity-50" disabled={Boolean(busy)} onClick={() => run(it.id, it.fn)}>
              {busy === it.id ? <Spinner className="mt-0.5 text-wb-ink-3" /> : <it.icon size={15} className="mt-0.5 flex-none text-wb-ink-2" aria-hidden="true" />}
              <span>
                <span className="block text-[12.5px] font-medium">{it.label}</span>
                <span className="block text-[11px] text-wb-ink-3">{it.hint}</span>
              </span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}

function ProjectName({ initial, onCommit }: { initial: string; onCommit: (name: string) => void }) {
  const [name, setName] = useState(initial);
  return (
    <input
      aria-label="Project name"
      className="h-7 w-[min(280px,30vw)] rounded-md border border-transparent bg-transparent px-1.5 text-[13px] font-medium hover:border-wb-line focus:border-wb-accent focus:outline-none"
      value={name}
      onChange={(e) => setName(e.target.value)}
      onBlur={() => name !== initial && onCommit(name)}
      onKeyDown={(e) => e.key === "Enter" && (e.target as HTMLInputElement).blur()}
    />
  );
}

export function TopBar({ wb, onOpenProjects }: { wb: Workbench; onOpenProjects: () => void }) {
  const p = wb.project;
  const approvedHere = p && p.approvedVersionId && p.approvedVersionId === p.currentVersionId;
  const approvedOther = p?.approvedVersionId && !approvedHere ? p.versions.find((v) => v.id === p.approvedVersionId) : null;

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      const t = e.target as HTMLElement;
      if (t.closest("input, textarea, select, [contenteditable]")) return;
      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "z" && !wb.job) {
        e.preventDefault();
        if (e.shiftKey) wb.redo();
        else wb.undo();
      }
    };
    document.addEventListener("keydown", onKey);
    return () => document.removeEventListener("keydown", onKey);
  }, [wb]);

  return (
    <header className="flex h-12 flex-none items-center gap-2 border-b border-wb-line bg-white px-3">
      <div className="flex items-center gap-2 pr-2">
        <span className="grid h-6 w-6 place-items-center rounded-md bg-wb-ink text-[11px] font-bold text-white" aria-hidden="true">
          W
        </span>
        <span className="hidden text-[13px] font-semibold md:inline">Workbench</span>
      </div>
      <span className="h-5 w-px bg-wb-line" aria-hidden="true" />
      {p ? (
        <ProjectName key={`${p.id}:${p.name}`} initial={p.name} onCommit={wb.rename} />
      ) : (
        <span className="px-1.5 text-[13px] text-wb-ink-3">New project</span>
      )}
      {p && (
        <span className="flex items-center gap-1 text-[11px] text-wb-ink-3" aria-live="polite">
          {wb.saveState === "saving" && <><Spinner className="h-3 w-3" /> Saving</>}
          {wb.saveState === "saved" && <><Cloud size={13} aria-hidden="true" /> Saved locally</>}
          {wb.saveState === "error" && <span className="flex items-center gap-1 text-red-700"><CloudOff size={13} aria-hidden="true" /> Not saved</span>}
        </span>
      )}
      <div className="ml-auto flex items-center gap-1.5">
        <ProviderBadge wb={wb} />
        <span className="mx-1 h-5 w-px bg-wb-line" aria-hidden="true" />
        <IconButton label="Undo (Ctrl+Z)" disabled={!p?.undoStack.length || Boolean(wb.job)} onClick={wb.undo}>
          <Undo2 size={15} />
        </IconButton>
        <IconButton label="Redo (Ctrl+Shift+Z)" disabled={!p?.redoStack.length || Boolean(wb.job)} onClick={wb.redo}>
          <Redo2 size={15} />
        </IconButton>
        {approvedOther && <Pill tone="green" title="An earlier version is approved">Approved: v{approvedOther.number}</Pill>}
        {approvedHere ? (
          <Button size="sm" variant="secondary" icon={<CircleCheck size={14} className="text-emerald-600" />} onClick={wb.unapprove} title="This version is approved. Click to withdraw approval.">
            Approved
          </Button>
        ) : (
          <Button size="sm" variant="secondary" icon={<Check size={14} />} disabled={!wb.version || wb.isPreviewing || Boolean(wb.job)} onClick={wb.approve}>
            Approve v{wb.version?.number ?? ""}
          </Button>
        )}
        <ExportMenu wb={wb} />
        <Button size="sm" variant="ghost" icon={<FolderOpen size={14} />} onClick={onOpenProjects}>
          Projects
        </Button>
      </div>
    </header>
  );
}
